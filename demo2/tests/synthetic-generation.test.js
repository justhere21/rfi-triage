import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import test from "node:test";
import { buildGeneratedDataset, RECIPE_VERSION } from "../scripts/lib/generate-synthetic.js";
import { parseGenerationArgs, runSyntheticGeneration, REPO_ROOT } from "../scripts/generate-synthetic.js";
import { checkItems, INPUT_FIELDS } from "../scripts/lib/check-items.js";
import { loadPreparedItems } from "../scripts/check-input.js";

const silent = { log() {}, error() {} };
const hash = (value) => createHash("sha256").update(value).digest("hex");
const sourcePaths = [
  "data/synthetic/synthetic-rfis.json", "data/synthetic/synthetic_emails.csv",
  "data/synthetic/synthetic_minutes.csv", "data/synthetic/synthetic_answer_key.csv",
  ...["items.json", "answer-key.json", "manifest.json", "validation-report.json"].map((name) => `data/prepared/synthetic/${name}`)
];
function fixture(t) {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), "rfi-generated-fictional-"));
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }));
  return { directory, output: path.join(directory, "generated") };
}

test("seeded construction produces ten optional cases across three types and is byte deterministic", () => {
  const dataset = buildGeneratedDataset({ seed: 42 });
  assert.deepEqual(dataset, buildGeneratedDataset({ seed: 42 }));
  assert.equal(dataset.report.valid, true);
  assert.equal(dataset.items.length, 10);
  assert.deepEqual(dataset.report.counts, { input_records: 10, answer_records: 10, rfi: 6, email: 2, minutes: 2 });
  assert.deepEqual(checkItems(dataset.items).errors, []);
  assert.ok(dataset.items.every((item) => item.provenance === "synthetic" && item.item_id.startsWith("GEN-42-")));
  assert.equal(dataset.manifest.recipe_version, RECIPE_VERSION);
  assert.match(dataset.manifest.original_case_authorship, /not generated by this script/);
  assert.equal("generated_at" in dataset.manifest, false);
  for (const source of dataset.manifest.source_files) assert.equal(source.sha256, hash(fs.readFileSync(path.join(REPO_ROOT, source.file))));
});

test("changing the seed constructs different fixture context without changing the intended recipe coverage", () => {
  const first = buildGeneratedDataset({ seed: 42 });
  const other = buildGeneratedDataset({ seed: 43 });
  assert.notDeepEqual(first.items, other.items);
  assert.notEqual(first.items[0].question_text, other.items[0].question_text);
  assert.notEqual(first.items[0].location, other.items[0].location);
  assert.deepEqual(first.manifest.records.map((row) => row.recipe_id), other.manifest.records.map((row) => row.recipe_id));
  assert.deepEqual(first.answerKey.map((row) => row.expected), other.answerKey.map((row) => row.expected));
  assert.notEqual(first.manifest.dataset_id, other.manifest.dataset_id);
  assert.equal(buildGeneratedDataset({ seed: 0 }).report.valid, true);
  assert.equal(buildGeneratedDataset({ seed: 4294967295 }).report.valid, true);
});

test("controlled mutations preserve missing evidence, explicit conflicts, and resolvable related paraphrases", () => {
  const { items, manifest, answerKey } = buildGeneratedDataset();
  const byRecipe = (recipe) => items.find((item) => manifest.records.find((record) => record.item_id === item.item_id).recipe_id === recipe);
  const expectedFor = (recipe) => answerKey.find((answer) => answer.item_id === byRecipe(recipe).item_id).expected;
  assert.equal(byRecipe("remove_required_location").location, "");
  assert.deepEqual(expectedFor("remove_required_location").labels, ["INCOMPLETE", "MISSING_LOCATION", "NEEDS_HUMAN_REVIEW"]);
  assert.deepEqual(byRecipe("remove_drawing_reference").drawing_refs, []);
  assert.deepEqual(expectedFor("remove_drawing_reference").labels, ["INCOMPLETE", "MISSING_DRAWING_REFERENCE", "NEEDS_HUMAN_REVIEW"]);
  assert.doesNotMatch(byRecipe("remove_drawing_reference").question_text, /two different|conflict|disagree|inconsisten/i);
  assert.equal(expectedFor("remove_drawing_reference").recommended_action, "revise");
  assert.deepEqual(byRecipe("declared_photo_not_attached").attachments, []);
  assert.deepEqual(expectedFor("declared_photo_not_attached").labels, ["INCOMPLETE", "MISSING_SUPPORTING_DOCUMENTATION", "NEEDS_HUMAN_REVIEW"]);
  assert.match(byRecipe("explicit_document_disagreement").question_text, /while specification/);
  assert.deepEqual(byRecipe("related_paraphrase").related_item_ids, [byRecipe("complete_single_question").item_id]);
  assert.deepEqual(byRecipe("repeat_conflict_in_minutes").related_item_ids, [byRecipe("explicit_document_disagreement").item_id]);
  assert.ok(answerKey.every((answer) => answer.review_status === "recipe_expectations_require_team_review"));
  assert.equal(new Set(manifest.records.map((record) => record.recipe_id)).size, 10);
});

test("recipe expectations and explanation remain outside every generated input", () => {
  const { items, answerKey } = buildGeneratedDataset();
  assert.deepEqual(items.map((item) => item.item_id), answerKey.map((answer) => answer.item_id));
  for (const item of items) {
    assert.ok(Object.keys(item).every((field) => INPUT_FIELDS.includes(field)));
    assert.ok(!Object.keys(item).some((field) => /expected|answer|labels|recipe|controlled_changes/.test(field)));
  }
});

test("generation dry-run makes no files and actual generation preserves all original sources and artifacts", (t) => {
  const files = fixture(t);
  const before = sourcePaths.map((file) => fs.readFileSync(path.join(REPO_ROOT, file)));
  assert.equal(runSyntheticGeneration(["--out-dir", files.output, "--dry-run"], { logger: silent }).exitCode, 0);
  assert.equal(fs.existsSync(files.output), false);
  const generated = runSyntheticGeneration(["--out-dir", files.output, "--seed", "23"], { logger: silent });
  assert.equal(generated.exitCode, 0);
  assert.deepEqual(fs.readdirSync(files.output).sort(), ["answer-key.json", "items.json", "manifest.json", "validation-report.json"]);
  assert.equal(loadPreparedItems(path.join(files.output, "items.json")).length, 10);
  for (const [index, file] of sourcePaths.entries()) assert.deepEqual(fs.readFileSync(path.join(REPO_ROOT, file)), before[index]);
  assert.equal(loadPreparedItems().length, 23);
});

test("generator rejects malformed seeds, missing values, and unknown CLI flags", () => {
  for (const seed of [-1, 4294967296, 1.5, "42", NaN, Infinity]) assert.throws(() => buildGeneratedDataset({ seed }), /Seed must be an integer/);
  for (const value of ["-1", "4294967296", "1.5", "bad", "Infinity"]) assert.throws(() => parseGenerationArgs(["--seed", value]), /Seed must be an integer/);
  for (const args of [["--seed"], ["--out-dir"], ["--input", "source.json"], ["--unknown"]]) assert.throws(() => parseGenerationArgs(args), /requires a value|Unknown argument/);
  assert.equal(parseGenerationArgs(["--seed", "0"]).seed, 0);
  assert.equal(parseGenerationArgs(["--seed", "4294967295"]).seed, 4294967295);
});

