test("generation refuses symlink destinations, linked artifacts and canonical-path escapes into primary data", (t) => {
  const files = fixture(t);
  const actual = path.join(files.directory, "actual");
  fs.mkdirSync(actual);
  fs.symlinkSync(actual, files.output);
  assert.throws(() => runSyntheticGeneration(["--out-dir", files.output], { logger: silent }), /symlink/);
  fs.unlinkSync(files.output);
  fs.symlinkSync(path.join(files.directory, "absent-target"), files.output);
  assert.throws(() => runSyntheticGeneration(["--out-dir", files.output, "--dry-run"], { logger: silent }), /symlink/);
  fs.unlinkSync(files.output);
  fs.mkdirSync(files.output);
  const raw = path.join(files.directory, "unchanged.json");
  fs.writeFileSync(raw, "do not change\n");
  fs.symlinkSync(raw, path.join(files.output, "items.json"));
  assert.throws(() => runSyntheticGeneration(["--out-dir", files.output], { logger: silent }), /symlink/);
  fs.unlinkSync(path.join(files.output, "items.json"));
  fs.linkSync(raw, path.join(files.output, "items.json"));
  assert.throws(() => runSyntheticGeneration(["--out-dir", files.output], { logger: silent }), /hard link/);
  assert.equal(fs.readFileSync(raw, "utf8"), "do not change\n");
  const alias = path.join(files.directory, "primary-alias");
  fs.symlinkSync(path.join(REPO_ROOT, "data/synthetic"), alias);
  assert.throws(() => runSyntheticGeneration(["--out-dir", path.join(alias, "new-output")], { logger: silent }), /must stay separate/);
});

test("generator CLI runs offline with no credentials and invalid options return nonzero without writes", (t) => {
  const files = fixture(t);
  const command = fileURLToPath(new URL("../scripts/generate-synthetic.js", import.meta.url));
  const env = { ...process.env, GEMINI_API_KEY: "", GEMINI_MODEL: "" };
  const valid = spawnSync(process.execPath, [command, "--out-dir", files.output, "--dry-run"], { cwd: files.directory, env, encoding: "utf8" });
  assert.equal(valid.status, 0, valid.stderr);
  assert.match(valid.stdout, /10 optional synthetic fixtures/);
  assert.equal(fs.existsSync(files.output), false);
  const invalid = spawnSync(process.execPath, [command, "--out-dir", files.output, "--seed", "-1"], { cwd: files.directory, env, encoding: "utf8" });
  assert.equal(invalid.status, 1);
  assert.equal(fs.existsSync(files.output), false);
  assert.equal(runSyntheticGeneration(["--help"], { logger: silent }).exitCode, 0);
});
